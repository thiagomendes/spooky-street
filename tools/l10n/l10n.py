#!/usr/bin/env python3
"""Language pack tools (S004 stream D1, docs/S004-lang-packs.md).

  python3 tools/l10n/l10n.py coverage          regenerate Core/Localization/FontCoverage.cs from the bundled fonts
  python3 tools/l10n/l10n.py packs --out DIR   build the downloadable packs (the pseudo pack) and catalog.json
  python3 tools/l10n/l10n.py check             CI check: FontCoverage.cs is current, every bundled table and the
                                               pseudo pack pass the font, placeholder and plural checks

The game validates every downloaded pack again on the device (PackValidator); these checks catch problems before a
pack is published. Packs are the StringTable JSON format (schema 2 adds plurals) plus a manifest in the catalog.
"""

import argparse
import hashlib
import json
import math
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
LOC_DIR = os.path.join(ROOT, "Assets", "SpookyStreet", "Content", "Resources", "Localization")
FONT_DIR = os.path.join(ROOT, "Assets", "SpookyStreet", "Content", "Resources", "Fonts")
FONTS = ["Andika-Regular.ttf", "Andika-Bold.ttf", "Sniglet-ExtraBold.ttf"]
COVERAGE_CS = os.path.join(ROOT, "Assets", "SpookyStreet", "Core", "Localization", "FontCoverage.cs")

PSEUDO_LOCALE = "qps-ploc"
PSEUDO_NAME = "[Þšéüðö]"
PSEUDO_EXPANSION = 0.35
PLAIN = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
# Must match PseudoLocalizer.Accented: look-alikes every bundled font draws (Sniglet is Latin-1 plus a few letters).
ACCENTED = "ábçðéƒghíȷkłmñöþqrštüvwxýžÅBÇÐÉFGHÍJKŁMÑÖÞQRŠTÜVWXÝŽ"

PLACEHOLDER = re.compile(r"\{(\d+)\}")
TAG = re.compile(r"</?[a-zA-Z]+(?:=[^>]*)?>")
PLURAL_REQUIRED = {"en": ["one", "other"], "de": ["one", "other"], "nl": ["one", "other"], "qps": ["one", "other"],
                   "pt": ["one", "other"], "fr": ["one", "other"], "es": ["one", "other"], "it": ["one", "other"]}


def font_coverage():
    from fontTools.ttLib import TTFont  # pinned in tools/requirements-ci.txt

    common = None
    for name in FONTS:
        cmap = set(TTFont(os.path.join(FONT_DIR, name)).getBestCmap())
        common = cmap if common is None else common & cmap
    return sorted(c for c in common if c >= 0x20)


def ranges(codepoints):
    out = []
    for c in codepoints:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def coverage_source():
    rs = ranges(font_coverage())
    lines = []
    row = []
    for start, end in rs:
        row.append(f"0x{start:04X}, 0x{end:04X}")
        if len(row) == 6:
            lines.append("            " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("            " + ", ".join(row) + ",")
    body = "\n".join(lines)
    count = sum(e - s + 1 for s, e in rs)
    return f"""// <auto-generated>
// Generated by tools/l10n/l10n.py coverage from {", ".join(FONTS)}. Do not edit by hand;
// `python3 tools/l10n/l10n.py check` (check-local.sh and CI) fails when it is out of date.
// </auto-generated>
namespace SpookyStreet.Core.Localization
{{
    /// <summary>
    /// The characters every bundled font draws ({count} code points): a pack whose text needs any other character is
    /// rejected (S004 §2.4 font coverage). Control characters (line breaks) are always allowed.
    /// </summary>
    public static class FontCoverage
    {{
        public const string Fonts = "{", ".join(FONTS)}";

        /// <summary>Inclusive code point ranges, sorted: start, end, start, end, …</summary>
        public static readonly int[] Ranges =
        {{
{body}
        }};

        public static bool Covers(int codePoint)
        {{
            if (codePoint < 0x20)
            {{
                return true;
            }}

            int lo = 0;
            int hi = Ranges.Length / 2 - 1;
            while (lo <= hi)
            {{
                int mid = (lo + hi) / 2;
                if (codePoint < Ranges[mid * 2])
                {{
                    hi = mid - 1;
                }}
                else if (codePoint > Ranges[mid * 2 + 1])
                {{
                    lo = mid + 1;
                }}
                else
                {{
                    return true;
                }}
            }}

            return false;
        }}
    }}
}}
"""


def pseudo(text):
    if not text:
        return text
    out = ["["]
    visible = 0
    i = 0
    while i < len(text):
        c = text[i]
        if c in "{<":
            close = "}" if c == "{" else ">"
            end = text.find(close, i + 1)
            if end > i:
                out.append(text[i:end + 1])
                i = end + 1
                continue
        k = PLAIN.find(c)
        out.append(ACCENTED[k] if k >= 0 else c)
        visible += 1
        i += 1
    pad = math.ceil(visible * PSEUDO_EXPANSION)
    out.append("".join("~" if j % 2 == 0 else "·" for j in range(pad)))
    out.append("]")
    return "".join(out)


def texts(entry):
    if "plural" in entry:
        return list(entry["plural"].values())
    return [entry["value"]]


def pseudo_table(english):
    entries = []
    for e in english["entries"]:
        p = {"key": e["key"]}
        if "plural" in e:
            p["plural"] = {k: pseudo(v) for k, v in e["plural"].items()}
        else:
            p["value"] = pseudo(e["value"])
        p["context"] = e.get("context", "")
        entries.append(p)
    return {"schemaVersion": english["schemaVersion"], "locale": PSEUDO_LOCALE, "nativeName": PSEUDO_NAME,
            "contentVersion": english.get("contentVersion", ""), "entries": entries}


def dump(table):
    return (json.dumps(table, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def check_table(table, english, covered, problems):
    """The same rules as PackValidator (fonts, placeholders, tags, plurals), for tables in the repo."""
    name = table["locale"]
    en = {e["key"]: e for e in english["entries"]}
    language = name.split("-")[0].lower()
    for ch in table.get("nativeName", ""):
        if ord(ch) >= 0x20 and ord(ch) not in covered:
            problems.append(f"{name}: nativeName needs U+{ord(ch):04X}")
    for e in table["entries"]:
        key = e["key"]
        for text in texts(e):
            for ch in text:
                if ord(ch) >= 0x20 and ord(ch) not in covered:
                    problems.append(f"{name}: {key} needs U+{ord(ch):04X} '{ch}', which a bundled font lacks")
        src = en.get(key)
        if src is None:
            continue
        if ("plural" in src) != ("plural" in e):
            problems.append(f"{name}: {key} plural forms differ from English")
            continue
        if "plural" in e:
            for need in PLURAL_REQUIRED.get(language, ["other"]):
                if need not in e["plural"]:
                    problems.append(f"{name}: {key} lacks plural form '{need}'")
        src_other = src["plural"]["other"] if "plural" in src else src["value"]
        other = e["plural"]["other"] if "plural" in e else e["value"]
        if set(PLACEHOLDER.findall(other)) != set(PLACEHOLDER.findall(src_other)):
            problems.append(f"{name}: {key} placeholders differ from English")
        if sorted(TAG.findall(other)) != sorted(TAG.findall(src_other)):
            problems.append(f"{name}: {key} rich-text tags differ from English")


def check_config(config, covered, problems):
    """languages.json: HTTPS catalog, built-in slots with drawable names."""
    url = config.get("catalogUrl", "")
    if url and not url.startswith("https://"):
        problems.append(f"languages.json: catalogUrl must be HTTPS ({url})")
    for slot in config.get("builtIn", []):
        if not re.fullmatch(r"[A-Za-z0-9]+(-[A-Za-z0-9]+)*", slot.get("locale", "")):
            problems.append(f"languages.json: bad built-in locale {slot!r}")
        for ch in slot.get("nativeName", ""):
            if ord(ch) not in covered:
                problems.append(f"languages.json: {slot['locale']} name needs U+{ord(ch):04X}")


def load(path):
    with open(path, "rb") as f:
        raw = f.read()
    if raw.startswith(b"\xef\xbb\xbf"):
        raise SystemExit(f"{path}: remove the UTF-8 byte order mark")
    return json.loads(raw.decode("utf-8"))


def build_packs(out_dir):
    english = load(os.path.join(LOC_DIR, "en.json"))
    os.makedirs(out_dir, exist_ok=True)
    data = dump(pseudo_table(english))
    file = f"{PSEUDO_LOCALE}.json"
    with open(os.path.join(out_dir, file), "wb") as f:
        f.write(data)
    manifest = {"locale": PSEUDO_LOCALE, "nativeName": PSEUDO_NAME, "contentVersion": english.get("contentVersion", ""),
                "tableSchema": english["schemaVersion"], "size": len(data),
                "sha256": hashlib.sha256(data).hexdigest(), "file": file, "development": True}
    catalog = {"catalogVersion": 1, "packs": [manifest]}
    with open(os.path.join(out_dir, "catalog.json"), "wb") as f:
        f.write(dump(catalog))
    print(f"wrote {out_dir}/catalog.json and {file} ({len(data)} bytes, sha256 {manifest['sha256'][:12]}…)")


def check():
    problems = []
    with open(COVERAGE_CS, encoding="utf-8") as f:
        if f.read() != coverage_source():
            problems.append("FontCoverage.cs is out of date: run python3 tools/l10n/l10n.py coverage")
    covered = set(font_coverage())
    english = load(os.path.join(LOC_DIR, "en.json"))
    for name in sorted(os.listdir(LOC_DIR)):
        if name.endswith(".json"):
            table = load(os.path.join(LOC_DIR, name))
            if "entries" not in table:
                check_config(table, covered, problems)
                continue
            check_table(table, english, covered, problems)
    check_table(pseudo_table(english), english, covered, problems)
    if problems:
        print("\n".join(problems))
        return 1
    print(f"l10n: coverage current, bundled tables and the pseudo pack pass ({len(english['entries'])} keys)")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("coverage")
    packs = sub.add_parser("packs")
    packs.add_argument("--out", default=os.path.join(ROOT, "build", "packs"))
    sub.add_parser("check")
    args = parser.parse_args()
    if args.command == "coverage":
        with open(COVERAGE_CS, "w", encoding="utf-8", newline="\n") as f:
            f.write(coverage_source())
        print(f"wrote {COVERAGE_CS}")
        return 0
    if args.command == "packs":
        build_packs(args.out)
        return 0
    return check()


if __name__ == "__main__":
    sys.exit(main())
